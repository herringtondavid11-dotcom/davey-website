import { expect, test } from '@playwright/test'
import { mockBackend, watchConsole } from './mock'

test('income premium: frequency, person, short-term, planned, scenarios, and charts', async ({ page }) => {
  test.setTimeout(60_000)
  const problems = watchConsole(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await mockBackend(page, { signedIn: true })
  await page.goto('/app/income')
  await expect(page.getByRole('img', { name: /Income by type/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /Income by person/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /Income by source/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /Recurring and short-term/ })).toBeVisible()
  await expect(page.getByRole('figure', { name: 'Current and forecast by month' })).toBeVisible()
  await expect(page.getByRole('figure', { name: 'Current and forecast for the year' })).toBeVisible()

  const created = page.waitForResponse((r) => r.url().includes('/rest/v1/income_sources') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Add income' }).click()
  await created
  const card = page.locator('.income-card')
  await card.getByLabel('Name').fill('Consulting')
  await card.getByLabel('Category').selectOption({ label: '1099 contract' })
  await card.getByLabel('Category').selectOption({ label: 'Real estate / rental' })
  await card.getByLabel('Category').selectOption({ label: 'Investments / dividends / interest' })
  await card.getByLabel('Category').selectOption({ label: 'W-2' })
  await expect(card.getByLabel('Person')).toHaveValue('user-1')
  await card.getByLabel('Person').selectOption({ label: 'Jordan' })
  await card.getByLabel('Person').selectOption({ label: 'Other' })
  await card.getByLabel('Other name').fill('Aunt May')
  await card.getByLabel('Other name').blur()
  await card.getByLabel('Person').selectOption({ label: 'Alex' })
  await expect(card.getByLabel('Other name')).toHaveCount(0)

  await card.getByLabel('Pay frequency').selectOption({ label: 'Twice a month' })
  await card.getByLabel('Pay frequency').selectOption({ label: 'Four times a month' })
  await card.getByLabel('Pay frequency').selectOption({ label: 'Weekly (52 a year)' })
  await card.getByLabel('Pay frequency').selectOption({ label: 'Every two weeks (26 a year)' })
  await card.getByLabel('Pay frequency').selectOption({ label: 'Custom' })
  await card.getByLabel('Times each month').fill('3')
  await card.getByLabel('Pay frequency').selectOption({ label: 'Every two weeks (26 a year)' })
  const each = card.getByLabel('Amount each time')
  await each.fill('2000')
  await each.blur()
  const summary = page.getByRole('region', { name: 'Income summary' })
  await expect(summary).toContainText('$52,000.00')

  await card.getByLabel('Term').selectOption({ label: 'One-time' })
  await card.getByLabel('Starts', { exact: true }).fill('2026-06')
  const forecast = page.getByRole('table', { name: 'Income forecast' })
  await expect(summary).toContainText('$2,000.00')
  await expect(forecast.getByRole('row', { name: /June 2026/ })).toContainText('$2,000')
  await expect(forecast.getByRole('row', { name: /January 2026/ })).toContainText('$0')

  await card.getByLabel('Term').selectOption({ label: 'A couple of times' })
  await card.getByLabel('Pay frequency').selectOption({ label: 'Once a month' })
  await card.getByLabel('Payments').fill('3')
  await card.getByLabel('Starts', { exact: true }).fill('2026-04')
  await expect(summary).toContainText('$6,000.00')
  await expect(forecast.getByRole('row', { name: /April 2026/ })).toContainText('$2,000')
  await expect(forecast.getByRole('row', { name: /July 2026/ })).toContainText('$0')

  await card.getByLabel('Term').selectOption({ label: 'Short-term' })
  await card.getByLabel('Amount each time').fill('1000')
  await card.getByLabel('Amount each time').blur()
  await card.getByLabel('Starts', { exact: true }).fill('2026-01')
  await card.getByLabel('Ends', { exact: true }).fill('2026-03')
  await expect(forecast.getByRole('row', { name: /March 2026/ })).toContainText('$1,000')
  await expect(forecast.getByRole('row', { name: /April 2026/ })).toContainText('$0')
  await expect(summary).toContainText('$3,000.00')

  await card.getByLabel('Term').selectOption({ label: 'Ongoing' })
  await card.getByLabel('Starts', { exact: true }).fill('')
  await card.getByLabel('Ends', { exact: true }).fill('')
  await card.getByLabel('Per month').fill('4000')
  await card.getByLabel('Per month').blur()
  await expect(summary).toContainText('$48,000.00')
  await expect(card.getByLabel('Per month')).toHaveValue('4000')

  await card.locator('details').click()
  await expect(card.getByLabel(/January 2026/)).toBeVisible()
  await card.locator('details').click()

  const plannedPost = page.waitForResponse((r) => r.url().includes('/rest/v1/income_sources') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Add planned' }).click()
  await plannedPost
  const planned = page.getByRole('region', { name: 'Planned' }).locator('.income-card')
  await planned.getByLabel('Name').fill('Bonus')
  await planned.getByLabel('Name').blur()
  await planned.getByLabel('Amount each time').fill('500')
  await planned.getByLabel('Amount each time').blur()
  await expect(summary).toContainText('$54,000.00')
  await expect(summary.getByText('Current per year').locator('..')).toContainText('$48,000.00')
  await page.getByRole('button', { name: 'Include planned' }).click()
  await expect(summary).toContainText('$48,000.00')
  await expect(summary).not.toContainText('$54,000.00')
  await page.getByRole('button', { name: 'Include planned' }).click()
  await expect(summary).toContainText('$54,000.00')

  const scenarioPost = page.waitForResponse((r) => r.url().includes('/rest/v1/income_scenarios') && r.request().method() === 'POST')
  await page.getByLabel('Raise on').selectOption({ label: 'Consulting' })
  await page.getByLabel('Raise as').selectOption({ label: 'Percent' })
  await page.getByLabel('Raise amount').fill('10')
  await page.getByLabel('Effective month').fill('2026-07')
  await page.getByRole('button', { name: 'Add raise' }).click()
  await scenarioPost
  const consulting = page.getByRole('region', { name: 'Income source Consulting' })
  await expect(consulting.getByLabel('Per month')).toHaveValue('4000')
  await expect(summary).toContainText('$56,400.00')

  const hypoPost = page.waitForResponse((r) => r.url().includes('/rest/v1/income_scenarios') && r.request().method() === 'POST')
  await page.getByLabel('Hypothetical name').fill('Side work')
  await page.getByLabel('Hypothetical amount').fill('1000')
  await page.getByRole('button', { name: 'Add hypothetical' }).click()
  await hypoPost
  await expect(summary).toContainText('$68,400.00')
  await expect(page.getByRole('img', { name: /Income by type/ })).toHaveAttribute('aria-label', /W-2/)
  await expect(page.getByRole('img', { name: /Income by person/ })).toHaveAttribute('aria-label', /Alex/)

  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '/tmp/income-premium-desktop.png', fullPage: false })
  await page.screenshot({ path: '/tmp/income-premium-desktop-full.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  const scroll = await page.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth])
  expect(scroll[0]).toBeLessThanOrEqual(scroll[1] + 1)
  await page.screenshot({ path: '/tmp/income-premium-phone.png', fullPage: false })
  await expect(page.locator('.tabbar').getByRole('link', { name: 'Income' })).toHaveCount(0)

  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.sidebar').getByRole('link', { name: 'Overview', exact: true }).click()
  await page.locator('.sidebar').getByRole('link', { name: 'Income', exact: true }).click()
  const back = page.getByRole('region', { name: 'Income source Consulting' })
  await expect(back.getByLabel('Name')).toHaveValue('Consulting')
  await expect(back.getByLabel('Pay frequency')).toHaveValue('monthly')
  await expect(back.getByLabel('Term')).toHaveValue('ongoing')
  await expect(back.getByLabel('Person')).toHaveValue('user-1')
  await expect(page.getByRole('region', { name: 'Income source Bonus' })).toBeVisible()
  await expect(page.getByText('10% raise')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Scenarios' }).getByText('Side work')).toBeVisible()
  expect(problems).toEqual([])
})
